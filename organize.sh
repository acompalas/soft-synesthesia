#!/usr/bin/env bash
# One-time tidy-up into the layout described in REPRODUCE.md. Moves data, deletes only regenerated figures.
set -o pipefail
say() { echo "  $*"; }
echo "== policies -> checkpoints/policies/"
mkdir -p checkpoints/policies
for p in "baseline_ep4500 baseline_ep4500" "baseline_ep5000 baseline_ep5000" "parkfixed_ep3600 park_ep3600" "parkfixed_ep5000 park_ep5000"; do
  set -- $p
  if [ -f checkpoints/eval/$1.pth ]; then { [ -e checkpoints/policies/$2.pth ] || cp checkpoints/eval/$1.pth checkpoints/policies/$2.pth; } && say "$2.pth"
  else say "MISSING checkpoints/eval/$1.pth"; fi
done
echo "== reconstruction shards -> rollouts/recon/<set>/"
mkdir -p rollouts/recon
[ -d rollouts/recon_shards ] && [ ! -e rollouts/recon/baseline_latest ] && mv rollouts/recon_shards rollouts/recon/baseline_latest && say "recon_shards -> recon/baseline_latest"
echo "== Fig. 7 recordings -> rollouts/fig7/<set>/"
mkdir -p rollouts/fig7
for d in rollouts/fig7_*; do
  [ -d "$d" ] || continue
  n=${d#rollouts/fig7_}
  [ -e rollouts/fig7/$n ] || { mv "$d" rollouts/fig7/$n && say "$d -> rollouts/fig7/$n"; }
  rm -f rollouts/fig7/$n/touch_rollout*.png rollouts/fig7/$n/touch_rollout*.gif   # old figures; remade in deliverables/
done
echo "== old figure and CNN-output locations (all regenerated by train_recon.sh / make_deliverables.sh)"
for d in results/shape_recon_compare results/shape_recon_baseline_latest rollouts/shape_recon_baseline_latest \
         rollouts/shape_recon_small rollouts/shape_recon_fake rollouts/shape_recon_results deliverables; do
  [ -e $d ] && rm -rf $d && say "removed $d"
done
for f in results/binary_fig7.png results/park_fig7_smoke.png results/park_fig7_smoke.gif; do   # superseded, tracked
  git ls-files --error-unmatch $f >/dev/null 2>&1 && git rm -q $f && say "git rm $f"
done
grep -qx "models/" .gitignore || { echo "models/" >> .gitignore; say "models/ added to .gitignore"; }
echo "done"
